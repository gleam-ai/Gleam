#!/usr/bin/env python3
"""Delete comments that carry no information.

The comment budget here is: explain *why*, never *what*, and only where a reader
would otherwise get it wrong. Everything else rots next to the code, so this
script removes it wholesale; authors re-add short English notes for the few
decisions that are genuinely non-obvious.

Only comments doing mechanical work survive, because deleting them changes
behaviour rather than readability:

  * toolchain directives   //go:embed, //go:build, //nolint, /* eslint-disable */
  * language pragmas, # type: ignore, # noqa, # pragma: no cover
  * provenance headers     licence, "Code generated ... DO NOT EDIT", shebangs
  * outstanding work       TODO / FIXME

Usage:

    python scripts/prune-comments.py --dry
    python scripts/prune-comments.py
    python scripts/prune-comments.py --inventory OUT
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

SCRIPTS = Path(__file__).resolve().parent
ROOT = SCRIPTS.parent
sys.path.insert(0, str(SCRIPTS))

from importlib import import_module  # noqa: E402

_policy = import_module("check-comments")
iter_source_files = _policy.iter_source_files
Scanner = _policy.Scanner

EXT_LANG = {
    ".go": "go",
    ".js": "js",
    ".mjs": "js",
    ".cjs": "js",
    ".ts": "ts",
    ".py": "py",
}

KEEP = re.compile(
    "|".join(
        [
            r"^\s*//\s*go:[a-z]",
            r"^\s*//\s*\+build",
            r"nolint|revive:|exhaustive:|staticcheck|nosec|lint:ignore",
            r"eslint-disable|eslint-env|eslint\b.*\*/",
            r"prettier-ignore|istanbul\s|coverage:",
            r"@ts-[a-z-]+|@jsx\b|@license|@preserve",
            r"^\s*#\s*(type:|noqa|pylint:|pragma:|isort:|mypy:|ruff:|fmt:)",
            r"^#!|coding[:=]",
            r"[Cc]opyright|SPDX-License|DO NOT EDIT|Code generated by",
            r"\bTODO\b|\bFIXME\b|\bXXX\b",
        ]
    )
)


def spans(text: str, lang: str) -> list[tuple[int, int]]:
    """Character ranges of every comment, including its start marker.

    Delegates to the policy gate's tokenizer so the two tools can never disagree
    about what a comment is - they used to, and the tools have to be the same
    authority for "is this line a comment".
    """
    return Scanner(lang, text).spans()


def prunable(
    text: str, start: int, end: int, lang: str, trailing: bool
) -> bool:
    """True when the comment holds no machine instruction and may be removed."""
    if KEEP.search(text[start:end]):
        return False
    line_start = text.rfind("\n", 0, start) + 1
    if text[line_start:start].strip():
        return trailing
    has_line_comment = text[start : start + 2] == "//" or (
        lang == "py" and text[start] == "#"
    )
    if not has_line_comment:
        body_end = end
        while body_end > start and text[body_end - 1] in " \t":
            body_end -= 1
        nxt = text.find("\n", body_end)
        tail = text[body_end : nxt if nxt >= 0 else len(text)]
        if tail.strip():
            return False
    return True


def prune(text: str, lang: str, trailing: bool = False) -> tuple[str, int]:
    """Strip comments that fail prunable(). Returns (new_text, removed_count)."""
    removals = [
        (s, e)
        for s, e in spans(text, lang)
        if prunable(text, s, e, lang, trailing)
    ]
    for start, end in reversed(removals):
        line_start = text.rfind("\n", 0, start) + 1
        if text[line_start:start].strip() == "":
            nxt = text.find("\n", end)
            stop = nxt + 1 if nxt >= 0 else len(text)
            text = text[:line_start] + text[stop:]
        else:
            text = text[:start].rstrip() + text[end:]
    text = re.sub(r"\n{3,}", "\n\n", text)
    return text, len(removals)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--dry", action="store_true")
    ap.add_argument(
        "--trailing", action="store_true", help="also drop comments after code"
    )
    ap.add_argument("--inventory")
    args = ap.parse_args()

    total = touched = 0
    kept: list[str] = []
    for path, lang in iter_source_files():
        with open(path, encoding="utf-8", newline="") as fh:
            text = fh.read()
        new, removed = prune(text, lang, args.trailing)
        if args.inventory:
            rel = path.relative_to(ROOT).as_posix()
            for s, e in spans(text, lang):
                if not prunable(text, s, e, lang, args.trailing):
                    kept.append(f"{rel}: {text[s:e].strip()[:160]}")
        if removed:
            total += removed
            touched += 1
            print(f"[prune] {path.relative_to(ROOT).as_posix()} -{removed}")
            if not args.dry and new != text:
                with open(path, "w", encoding="utf-8", newline="") as fh:
                    fh.write(new)

    if args.inventory:
        Path(args.inventory).write_text(
            "\n".join(kept) + "\n", encoding="utf-8"
        )
        print(f"[prune] kept {len(kept)} comment(s) -> {args.inventory}")
    mode = "dry run" if args.dry else "written"
    print(
        f"[prune-comments] removable comments: {total} in {touched} file(s) ({mode})"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
